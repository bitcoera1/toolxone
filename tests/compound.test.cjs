test('calculation assumptions in compound FAQ and schema agree', () => {
    let faq;
    let schema;
    const registry = {
        register(type, id, value) {
            if (type === 'faq' && id === 'compound-interest-calculator') faq = value;
        }
    };
    const context = {
        console: quietConsole, ToolXoneContentRegistry: registry,
        ToolXoneSchemaRegistry: { register(id, value) { schema = value; } }
    };
    context.window = context;
    vm.createContext(context);
    vm.runInContext(read('js/content/content-data-finance.js'), context);
    vm.runInContext(read('js/seo/schemas/compound-interest-calculator-schema.js'), context);
    const questions = [
        'Does adding monthly contributions affect compound growth?',
        'Does compounding frequency affect the result?',
        'Is the annual interest rate an effective annual yield or APY?',
        'How are partial compounding periods handled?',
        'Can I enter a duration that includes part of a year?',
        'How is daily compounding approximated?',
        'What does the growth percentage mean?',
        'What happens at zero interest?'
    ];
    for (const question of questions) {
        const visible = faq.find(item => item.question === question);
        const structured = schema.schema.faq.find(item => item.question === question);
        assert.ok(visible && structured, question);
        assert.equal(visible.answer, structured.answer, question);
    }
});
