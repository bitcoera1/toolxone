for (const [name, inputs, focused] of invalid) {
    test('reject ' + name, () => {
        const h = harness(inputs);
        h.run();
        assert.equal(h.alerts.length, 1);
        assert.equal(h.focused, focused);
        assert.equal(h.values.size, 0);
        assert.equal(h.document.getElementById('compoundResult').innerHTML, '');
        assert.deepEqual(h.recorded, []);
    });
}

test('overflow is rejected without publishing a nonfinite result or statistics', () => {
    const h = harness({ rate: 1000, years: 100, frequency: 365 });
    h.run();
    assert.equal(h.alerts.length, 1);
    assert.match(h.alerts[0], /invalid result/);
    assert.equal(h.values.size, 0);
    assert.equal(h.document.getElementById('compoundResult').innerHTML, '');
    assert.deepEqual(h.recorded, []);
});

test('maximum duration remains accepted when the result is finite', () => {
    const h = harness({ years: 100, rate: 0 });
    h.run();
    assert.deepEqual(h.alerts, []);
    assert.equal(h.values.get('Future Value'), 121000);
});

test('Enter calculates once and reset preserves the existing Monthly reset default', () => {
    const h = harness();
    let prevented = false;
    h.listeners.get('keydown')({
        key: 'Enter', target: { matches: () => true },
        preventDefault() { prevented = true; }
    });
    assert.equal(prevented, true);
    near(h.values.get('Future Value'), 2407.7578344649);
    assert.deepEqual(h.recorded, ['compound-interest-calculator']);
    h.context.resetCompound();
    for (const id of ['principal', 'monthly', 'rate', 'years']) {
        assert.equal(h.document.getElementById(id).value, '');
    }
    assert.equal(h.document.getElementById('frequency').value, '12');
    assert.equal(h.document.getElementById('compoundResult').classList.contains('active'), false);
    assert.equal(h.document.getElementById('growthBars').style.display, 'none');
    assert.equal(h.document.getElementById('investmentBar').style.width, '0%');
    assert.equal(h.document.getElementById('interestBar').style.width, '0%');
});

